"""Cache task-background primary papers for review, never candidate queries."""

import argparse
import json
from pathlib import Path

import httpx

TITLES = {
    "cpeb3_crowding": "Molecular Crowding Favors Reactivity of a Human Ribozyme Under Physiological Ionic Conditions",
    "azoarcus_folding": "Assembly of core helices and rapid tertiary folding of a small bacterial group I ribozyme",
    "aminoacylation_substrate": "Small-molecule-substrate interactions with a self-aminoacylating ribozyme",
    "yeast_trna_transport": "Retrograde movement of tRNAs from the cytoplasm to the nucleus in Saccharomyces cerevisiae",
    "gfp_capture": "RNA aptamer capture of macromolecular complexes for mass spectrometry analysis",
    "nelf_complex": "Structural basis of the human negative elongation factor NELF-B/C/E ternary complex",
    "twister_computation": "Cleaning Up Mechanistic Debris Generated by Twister Ribozymes Using Computational RNA Enzymology",
    "tpr_circle": "Rolling circle RNA synthesis catalyzed by RNA",
    "ts_simulation": "Model for the Functional Active State of the TS Ribozyme from Molecular Simulation",
    "cpeb3_nmr": "Secondary structure confirmation and localization of Mg2+ ions in the mammalian CPEB3 ribozyme",
    "rice_twister_qm": "Molecular mechanism of the site-specific self-cleavage of the RNA phosphodiester backbone by a twister ribozyme",
    "cpeb3_inhibition": "Inhibition of CPEB3 ribozyme elevates CPEB3 protein expression and polyadenylation of its target mRNAs, and enhances object location memory",
    "ts_shape": "SHAPE probing pictures Mg2+-dependent folding of small self-cleaving ribozymes",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, required=True)
    root = parser.parse_args().output
    root.mkdir(parents=True, exist_ok=True)
    with httpx.Client(timeout=60, follow_redirects=True, trust_env=False) as client:
        for key, title in TITLES.items():
            query = 'TITLE:"' + title + '"'
            path = root / f"{key}.json"
            if not path.exists():
                response = client.get(
                    "https://www.ebi.ac.uk/europepmc/webservices/rest/search",
                    params={"query": query, "format": "json", "resultType": "core", "pageSize": 3},
                )
                response.raise_for_status()
                path.write_text(json.dumps({"query": query, "response": response.json()}, indent=2))
            data = json.loads(path.read_text())
            records = data["response"]["resultList"]["result"]
            if not records:
                print(json.dumps({"id": key, "status": "not_found"}), flush=True)
                continue
            record = next((r for r in records if r.get("pmcid")), records[0])
            pmc = record.get("pmcid")
            if pmc and not (root / f"{key}.xml").exists():
                response = client.get(
                    f"https://www.ebi.ac.uk/europepmc/webservices/rest/{pmc}/fullTextXML"
                )
                if response.status_code == 200:
                    (root / f"{key}.xml").write_text(response.text)
            print(
                json.dumps(
                    {
                        "id": key,
                        "title": record.get("title"),
                        "doi": record.get("doi"),
                        "date": record.get("firstPublicationDate"),
                        "pmcid": pmc,
                        "abstract": record.get("abstractText"),
                    }
                ),
                flush=True,
            )


if __name__ == "__main__":
    main()
